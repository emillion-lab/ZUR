#!/usr/bin/env python3
"""Верни координати на спирките.

Точките в patch_goto.py бяха написани по памет и шест от десет се
разминаваха — най-лошите с двеста метра. За град, който не познавам,
това е недопустимо: шофьорът отива на грешно място и няма как да
разбере, че приложението греши.

Стойностите тук са сверени срещу Google Places (август 2026). Всяка е
записана с шест знака и с бележка колко е било разминаването, за да
личи, че е проверявана, а не преписвана наново.
"""
import re
import sys

JS = 'transport.js'
MARK = 'PLACES-VERIFIED'

BLOCK = """  // PLACES-VERIFIED (авг. 2026, сверено с Google Places)
  // Стари стойности бяха писани по памет; в скобите е разминаването.
  var PLACES = {
    'HB':            [47.378036,  8.540377],   // беше 47.3779/8.5403 — вярно
    'Sihlquai':      [47.381159,  8.537139],   // беше 47.3800/8.5350 — 200 м встрани
    'Sihlquai/HB':   [47.381159,  8.537139],
    'Busbahnhof':    [47.381159,  8.537139],
    'Oerlikon':      [47.411487,  8.544181],   // вярно
    'Stadelhofen':   [47.366588,  8.548439],   // беше 47.3663 — 30 м
    'Flughafen':     [47.450375,  8.562402],   // беше 47.4515 — 130 м встрани
    'Bahnhofquai':   [47.377546,  8.541740],   // беше 47.3771/8.5419 — 60 м
    'Central':       [47.376526,  8.544372],   // беше 47.3769/8.5431 — 100 м
    'Bellevue':      [47.367118,  8.545099],   // беше 47.3668/8.5453 — 40 м
    'Paradeplatz':   [47.369732,  8.538909],   // нова
    'Stauffacher':   [47.373592,  8.529596],   // нова
    'Enge':          [47.364240,  8.531458]    // нова
  };

  // Летищните редове нямат спирка — всички водят до терминала
  var AIRPORT = [47.450375, 8.562402];
"""


def main():
    src = open(JS, encoding='utf-8').read()
    if MARK in src:
        print('координатите вече са сверени')
        return

    # маха стария блок PLACES заедно с AIRPORT
    pat = re.compile(
        r'  // GOTO-ZONE.*?var AIRPORT = \[[^\]]*\];\n', re.S)
    if not pat.search(src):
        print('ГРЕШКА: не намирам стария блок с координати')
        sys.exit(1)
    src = pat.sub(BLOCK, src, count=1)

    open(JS, 'w', encoding='utf-8').write(src)
    print('координатите са сверени срещу Google Places')


if __name__ == '__main__':
    main()
